def _load_system(skill: dict) -> str:
    if skill.get("system"):
        return skill["system"]
    base = Path(__file__).resolve().parent.parent / "templates"
    parts = [
        skill.get("file_prefix", "")
        + (base / skill["from_file"]).read_text(encoding="utf-8")
    ]
    for extra in skill.get("extra_files", []):
        parts.append("\n\n===== 页面文本模板（逐字遵循） =====\n")
        parts.append((base / extra).read_text(encoding="utf-8"))
    return "\n".join(parts)


@functools.lru_cache(maxsize=1)
def get_skills() -> list[dict]:
    """返回带 system 全文的技能列表。"""
    out = []
    for s in SKILLS:
        item = dict(s)
        item["system_full"] = _load_system(s)
        out.append(item)
    return out


def find_skill(name: str) -> dict | None:
    for s in get_skills():
        if s["name"] == name:
            return s
    return None


